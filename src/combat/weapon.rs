#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum Caliber {
    NineMm,        // 9x19mm
    FortyFiveAcp,  // .45 ACP
    TwelveGauge,   // 12 Gauge Shotgun Shell
    FiveFiveSix,   // 5.56x45mm NATO
    SevenSixTwo,   // 7.62x39mm / 7.62x51mm
    ThreeZeroEight,// .308 Winchester
    ThreeHundredWin, // .300 Winchester Magnum
    FiftyBmg,      // .50 BMG Anti-Materiel
    FortyMmGrenade,// 40mm HE Grenade
    MeleeBlunt,
    MeleeSharp,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum FireMode {
    SemiAuto,
    FullAuto,
    Burst,
    PumpAction,
    BoltAction,
    Melee,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct WeaponStats {
    pub weapon_id: String,
    pub name: String,
    pub caliber: Caliber,
    pub fire_mode: FireMode,
    pub base_damage: f32,
    pub headshot_multiplier: f32,
    pub rounds_per_minute: u32,
    pub mag_capacity: u32,
    pub current_ammo: u32,
    pub effective_range_m: f32,
    pub bullet_speed_mps: f32,
    pub spread_rad: f32,
    pub recoil_v: f32,
    pub recoil_h: f32,
    pub noise_radius_m: f32, // Sound event radius alerting zombies
    pub durability_loss_per_shot: f32,
    pub current_durability: f32,
    // Attachment IDs
    pub optic: Option<String>,
    pub suppressor: Option<String>,
    pub extended_mag: Option<String>,
    pub tactical: Option<String>,
}

impl WeaponStats {
    pub fn is_melee(&self) -> bool {
        matches!(self.fire_mode, FireMode::Melee)
    }

    pub fn can_fire(&self) -> bool {
        if self.is_melee() {
            self.current_durability > 0.0
        } else {
            self.current_ammo > 0 && self.current_durability > 0.0
        }
    }

    pub fn fire(&mut self) -> bool {
        if !self.can_fire() {
            return false;
        }

        if !self.is_melee() {
            self.current_ammo -= 1;
        }

        self.current_durability = (self.current_durability - self.durability_loss_per_shot).max(0.0);
        true
    }

    pub fn reload(&mut self, available_ammo: u32) -> u32 {
        if self.is_melee() {
            return 0;
        }

        let max_cap = self.effective_mag_capacity();
        let needed = max_cap.saturating_sub(self.current_ammo);
        let to_load = needed.min(available_ammo);
        self.current_ammo += to_load;
        to_load
    }

    pub fn effective_noise_radius(&self) -> f32 {
        if self.suppressor.is_some() {
            (self.noise_radius_m * 0.20).max(10.0) // 80% noise reduction
        } else {
            self.noise_radius_m
        }
    }

    pub fn attach_mod(&mut self, attachment_id: &str) {
        if attachment_id.starts_with("optic_") || attachment_id.starts_with("scope_") {
            self.optic = Some(attachment_id.to_string());
        } else if attachment_id.starts_with("muzzle_") || attachment_id == "suppressor" {
            self.suppressor = Some(attachment_id.to_string());
        } else if attachment_id.starts_with("mag_") {
            self.extended_mag = Some(attachment_id.to_string());
        } else if attachment_id.starts_with("tactical_") {
            self.tactical = Some(attachment_id.to_string());
        }
    }

    pub fn detach_mod(&mut self, slot: AttachmentSlot) -> Option<String> {
        match slot {
            AttachmentSlot::Optic => self.optic.take(),
            AttachmentSlot::Muzzle => self.suppressor.take(),
            AttachmentSlot::Magazine => {
                let mag = self.extended_mag.take();
                if self.current_ammo > self.mag_capacity {
                    self.current_ammo = self.mag_capacity;
                }
                mag
            }
            AttachmentSlot::Tactical => self.tactical.take(),
        }
    }

    pub fn is_suppressed(&self) -> bool {
        self.suppressor.is_some()
    }

    pub fn effective_mag_capacity(&self) -> u32 {
        let bonus = self.extended_mag.as_deref()
            .and_then(get_stock_attachment)
            .map(|a| a.mag_capacity_bonus)
            .unwrap_or(0);
        self.mag_capacity + bonus
    }

    pub fn effective_zoom(&self) -> f32 {
        self.optic.as_deref()
            .and_then(get_stock_attachment)
            .map(|a| a.zoom_multiplier)
            .unwrap_or(1.0)
    }

    pub fn effective_spread(&self) -> f32 {
        let mut spread = self.spread_rad;
        if let Some(optic) = self.optic.as_deref().and_then(get_stock_attachment) {
            spread *= optic.spread_multiplier;
        }
        if let Some(tac) = self.tactical.as_deref().and_then(get_stock_attachment) {
            spread *= tac.spread_multiplier;
        }
        spread
    }

    pub fn effective_recoil(&self) -> (f32, f32) {
        let mut v = self.recoil_v;
        let mut h = self.recoil_h;
        if let Some(muzzle) = self.suppressor.as_deref().and_then(get_stock_attachment) {
            v *= muzzle.recoil_v_multiplier;
            h *= muzzle.recoil_h_multiplier;
        }
        if let Some(optic) = self.optic.as_deref().and_then(get_stock_attachment) {
            v *= optic.recoil_v_multiplier;
            h *= optic.recoil_h_multiplier;
        }
        (v, h)
    }

    pub fn has_tactical_light(&self) -> bool {
        self.tactical.as_deref() == Some("tactical_flashlight")
    }

    pub fn has_laser(&self) -> bool {
        self.tactical.as_deref() == Some("tactical_laser")
    }
}

